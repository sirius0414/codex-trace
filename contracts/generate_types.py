#!/usr/bin/env python3
"""Generate TypeScript payload types from trajectory.schema.json (no dependencies)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DIRECTORY = Path(__file__).resolve().parent


def literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(schema: dict, depth: int = 0) -> str:
    if "$ref" in schema:
        prefix = "#/$defs/"
        reference = schema["$ref"]
        if not reference.startswith(prefix):
            raise ValueError(f"Unsupported external schema reference: {reference}")
        return reference[len(prefix) :]
    if "const" in schema:
        return literal(schema["const"])
    if "enum" in schema:
        return " | ".join(map(literal, schema["enum"]))
    for union in ("oneOf", "anyOf"):
        if union in schema:
            return " | ".join(f"({render(branch, depth)})" for branch in schema[union])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{render(schema['items'], depth)}>"
    if kind == "object":
        if schema.get("additionalProperties") is not False:
            raise ValueError("Contract objects must reject undeclared properties")
        required = schema.get("required", [])
        properties = schema.get("properties", {})
        if not properties:
            return "Record<string, never>"
        lines = ["{"]
        for name, prop in properties.items():
            optional = "" if name in required else "?"
            lines.append(f"{'  ' * (depth + 1)}{literal(name)}{optional}: {render(prop, depth + 1)};")
        lines.append(f"{'  ' * depth}}}")
        return "\n".join(lines)
    scalar_types = {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}
    if kind in scalar_types:
        return scalar_types[kind]
    raise ValueError(f"Unsupported schema shape: {schema}")


def generate() -> str:
    schema = json.loads((DIRECTORY / "trajectory.schema.json").read_text())
    lines = [
        "// Generated by contracts/generate_types.py. Do not edit by hand.",
        "// JSON Schema is authoritative for bounds and runtime validation.",
        "export const SCHEMA_VERSION = \"1.0.0\" as const;",
        "",
    ]
    for name, definition in schema["$defs"].items():
        lines.extend([f"export type {name} = {render(definition)};", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in types are stale")
    options = parser.parse_args()
    target = DIRECTORY / "types.ts"
    expected = generate()
    if options.check:
        if not target.exists() or target.read_text() != expected:
            parser.error("contracts/types.ts is stale; run python3 contracts/generate_types.py")
    else:
        target.write_text(expected)


if __name__ == "__main__":
    main()
